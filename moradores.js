// Script de Consulta de Moradores Operacional
document.addEventListener("DOMContentLoaded", () => {
    const selectBloco = document.getElementById("select-bloco");
    const selectApto = document.getElementById("select-apto");
    const displaySection = document.getElementById("morador-display");
    const displayLocalizacao = document.getElementById("display-localizacao");
    const contatosContainer = document.getElementById("contatos-container");

    // Array completo dos blocos solicitados de A até Z
    const blocos = "ABCDEFGHIJKLMNOPQRSTUVWXYZ".split("");

    // Popular combo de blocos
    blocos.forEach(bloco => {
        const option = document.createElement("option");
        option.value = bloco;
        option.textContent = `Bloco ${bloco}`;
        selectBloco.appendChild(option);
    });

    // Escuta mudança do bloco para liberar e filtrar apartamentos
    selectBloco.addEventListener("change", () => {
        const blocoSelecionado = selectBloco.value;
        selectApto.innerHTML = '<option value="">Selecione o Apartamento</option>';
        
        if (!blocoSelecionado) {
            selectApto.disabled = true;
            displaySection.classList.add("hidden");
            return;
        }

        // Buscar moradores salvos para mapear os apartamentos existentes daquele bloco
        const moradores = JSON.parse(localStorage.getItem("moradores") || "[]");
        const aptosFiltrados = moradores
            .filter(m => m.bloco === blocoSelecionado)
            .map(m => m.apartamento);

        // Remover duplicados e ordenar numericamente
        const aptosUnicos = [...new Set(aptosFiltrados)].sort((a, b) => parseInt(a) - parseInt(b));

        if(aptosUnicos.length > 0) {
            aptosUnicos.forEach(apto => {
                const option = document.createElement("option");
                option.value = apto;
                option.textContent = `Apto ${apto}`;
                selectApto.appendChild(option);
            });
        } else {
            // Fallback preventivo caso a listagem padrão não carregue para o bloco
            [101, 102, 103, 104].forEach(apto => {
                const option = document.createElement("option");
                option.value = apto.toString();
                option.textContent = `Apto ${apto}`;
                selectApto.appendChild(option);
            });
        }

        selectApto.disabled = false;
        displaySection.classList.add("hidden");
    });

    // Escuta seleção do apartamento para renderizar ficha cadastral completa
    selectApto.addEventListener("change", () => {
        const bloco = selectBloco.value;
        const apto = selectApto.value;

        if (!bloco || !apto) {
            displaySection.classList.add("hidden");
            return;
        }

        renderFichaMorador(bloco, apto);
    });

    function renderFichaMorador(bloco, apto) {
        const moradores = JSON.parse(localStorage.getItem("moradores") || "[]");
        // Busca a unidade específica correspondente
        const unidade = moradores.find(m => m.bloco === bloco && m.apartamento === apto);

        displayLocalizacao.textContent = `Bloco ${bloco} - Apartamento ${apto}`;
        contatosContainer.innerHTML = "";

        if (unidade && unidade.contatos && unidade.contatos.length > 0) {
            unidade.contatos.forEach(contato => {
                if(!contato.nome && !contato.telefone) return;
                
                const card = document.createElement("div");
                card.className = "contato-card";
                
                // Trata strings numéricas para links puros sem formatação incorreta
                const limpoTelefone = contato.telefone.replace(/\D/g, "");
                
                card.innerHTML = `
                    <h4><i class="fa-solid fa-user"></i> ${contato.nome || 'Não Informado'}</h4>
                    <p><i class="fa-solid fa-phone-volume"></i> Telefone: ${contato.telefone}</p>
                    <div class="contato-actions">
                        <a href="https://wa.me/55${limpoTelefone}?text=Olá,%20sou%20da%20portaria%20do%20Residencial%20Jaborandi." target="_blank" class="btn-action-wa">
                            <i class="fa-brands fa-whatsapp"></i> WhatsApp
                        </a>
                        <a href="tel:+55${limpoTelefone}" class="btn-action-call">
                            <i class="fa-solid fa-phone"></i> Ligar
                        </a>
                    </div>
                `;
                contatosContainer.appendChild(card);
            });
        } else {
            contatosContainer.innerHTML = `
                <div style="grid-column: 1/-1; text-align: center; padding: 20px; color: var(--text-muted);">
                    <i class="fa-solid fa-triangle-exclamation" style="font-size: 2rem; margin-bottom:10px;"></i>
                    <p>Nenhum morador registrado para esta unidade no sistema.</p>
                </div>
            `;
        }
        displaySection.classList.remove("hidden");
    }

    // Interceptador para Deep Linking via URL (Permite links diretos vindos da barra de busca global)
    const urlParams = new URLSearchParams(window.location.search);
    const urlBloco = urlParams.get('bloco');
    const urlApto = urlParams.get('apto');

    if(urlBloco && urlApto) {
        setTimeout(() => {
            selectBloco.value = urlBloco;
            selectBloco.dispatchEvent(new Event('change'));
            selectApto.value = urlApto;
            selectApto.dispatchEvent(new Event('change'));
        }, 200);
    }
});